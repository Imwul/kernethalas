import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * The local source overlay holds the rulebook's original wording. It is only for the owner's
 * own machine: `vite dev` uses it, but production builds swap it for an empty stub unless
 * LOCAL_SOURCE=1 is set explicitly (never do that for a public deploy).
 */
function stripLocalSource(): Plugin {
  let keep = false;
  return {
    name: 'strip-local-source',
    configResolved(c) {
      keep = c.command === 'serve' || process.env.LOCAL_SOURCE === '1';
    },
    load(id) {
      if (!keep && id.replace(/\\/g, '/').endsWith('/src/local/source-overlay.json')) return 'null';
      return null;
    },
  };
}

/**
 * After the build, write one HTML file per route (dist/ref/prone.html …) carrying that page's
 * title, description and link-preview tags. The SPA still boots from the same assets; the files
 * only make shared links and search results show the right page. Served via cleanUrls on Vercel.
 */
function prerenderMeta(): Plugin {
  let outDir = 'dist';
  return {
    name: 'prerender-meta',
    apply: 'build',
    configResolved(c) {
      outDir = c.build.outDir;
    },
    async closeBundle() {
      const { readFileSync, writeFileSync, mkdirSync } = await import('node:fs');
      const { dirname, join } = await import('node:path');
      const { pageMeta, allRoutes, SITE_URL, SITE_NAME } = await import('./src/lib/meta');
      const base = readFileSync(join(outDir, 'index.html'), 'utf8');
      const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
      const render = (path: string) => {
        const m = pageMeta(path);
        const url = SITE_URL + (path === '/' ? '/' : path);
        const tags = [
          `<link rel="canonical" href="${url}" />`,
          `<meta property="og:type" content="website" />`,
          `<meta property="og:site_name" content="${SITE_NAME}" />`,
          `<meta property="og:title" content="${esc(m.title)}" />`,
          `<meta property="og:description" content="${esc(m.description)}" />`,
          `<meta property="og:url" content="${url}" />`,
          `<meta property="og:image" content="${SITE_URL}/og.png" />`,
          `<meta property="og:image:width" content="1200" />`,
          `<meta property="og:image:height" content="630" />`,
          `<meta property="og:locale" content="ko_KR" />`,
          `<meta name="twitter:card" content="summary_large_image" />`,
        ].join('\n    ');
        return base
          .replace(/<title>[^<]*<\/title>/, `<title>${esc(m.title)}</title>`)
          .replace(/<meta name="description" content="[^"]*" \/>/, `<meta name="description" content="${esc(m.description)}" />\n    ${tags}`);
      };
      const routes = allRoutes();
      for (const path of routes) {
        const file = path === '/' ? join(outDir, 'index.html') : join(outDir, `${path.slice(1)}.html`);
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, render(path));
      }
      this.info?.(`prerendered meta for ${routes.length} routes`);
    },
  };
}

/**
 * Offline support: write dist/sw.js with the exact files of this build. The app shell and its
 * hashed assets are cached on install; navigations try the network first and fall back to the
 * cached shell, so the reference keeps working at a table with no signal. Fonts from Google Fonts
 * are cached as they are used. A new build gets a new cache name and the old one is removed.
 */
function offlineWorker(): Plugin {
  let outDir = 'dist';
  return {
    name: 'offline-worker',
    apply: 'build',
    enforce: 'post',
    configResolved(c) {
      outDir = c.build.outDir;
    },
    async closeBundle() {
      const { readdirSync, readFileSync, writeFileSync } = await import('node:fs');
      const { join } = await import('node:path');
      const { createHash } = await import('node:crypto');
      const assets = readdirSync(join(outDir, 'assets')).map((f) => `/assets/${f}`);
      const statics = ['/', '/index.html', '/favicon.svg', '/manifest.webmanifest', '/icon-192.png', '/icon-512.png'];
      const precache = [...statics, ...assets];
      const body = `/* generated by vite.config.ts → offlineWorker */
const VERSION = '__VERSION__';
const SHELL = 'ossuary-shell-' + VERSION;
const FONTS = 'ossuary-fonts-v1';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('ossuary-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // pages: network first (fresh deploys win), cached shell when offline
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() => caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((r) => r || caches.match('/index.html', { ignoreVary: true }))),
    );
    return;
  }
  // hashed build files and icons: cache first
  if (url.origin === self.location.origin) {
    // ignoreVary: dev/preview servers send Vary: Origin, and module scripts carry an Origin header
    event.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
    return;
  }
  // Google Fonts: keep what has been used, refresh in the background
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(
      caches.open(FONTS).then((cache) =>
        cache.match(req, { ignoreVary: true }).then((hit) => {
          const net = fetch(req).then((res) => { if (res.ok || res.type === 'opaque') cache.put(req, res.clone()); return res; }).catch(() => hit);
          return hit || net;
        }),
      ),
    );
  }
});
`;
      // the cache name changes whenever the files, the page or this worker's own code change
      const version = createHash('sha256').update(precache.join('|') + readFileSync(join(outDir, 'index.html'), 'utf8') + body).digest('hex').slice(0, 12);
      const sw = body.replace('__VERSION__', version);
      writeFileSync(join(outDir, 'sw.js'), sw);
      this.info?.(`offline worker: ${precache.length} files, version ${version}`);
    },
  };
}

export default defineConfig({
  plugins: [react(), stripLocalSource(), prerenderMeta(), offlineWorker()],
  test: { environment: 'node' },
} as never);
