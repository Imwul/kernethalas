import { expect, test } from '@playwright/test';

test('physical rolls focus the next field, undo linked effects, and carry tension across restored locations', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 });
  await page.goto('/play');
  const stages = page.getByRole('navigation', { name: '플레이 단계' });
  const explore = page.getByRole('region', { name: '장소 탐험' });
  const room = explore.getByRole('button', { name: '방', exact: true });
  await room.click();
  const tension = explore.getByRole('combobox', { name: '긴장 주사위 크기' });
  const tensionValue = explore.getByRole('textbox', { name: '긴장 주사위 굴린 값' });
  await tension.selectOption('4');
  await tensionValue.fill('2');
  await tensionValue.press('Enter');
  const darkness = explore.getByRole('region', { name: '짙어지는 어둠', exact: true });
  const darknessValue = darkness.getByRole('textbox', { name: '직접 굴린 값' });
  await expect(darknessValue).toBeFocused();
  await darknessValue.fill('69');
  await darknessValue.press('Enter');
  const encounter = explore.getByRole('region', { name: '조우 판정', exact: true });
  await expect(encounter.getByRole('textbox', { name: '직접 굴린 값' })).toBeFocused();
  const undo = page.getByRole('button', { name: '직전 굴림 되돌리기' });
  await expect(undo).toBeEnabled();
  await undo.click();
  await expect(encounter).toHaveCount(0);
  await expect(darkness.getByRole('status')).not.toContainText('방에 들어갈 때마다');
  await darknessValue.fill('69');
  await darknessValue.press('Enter');

  const journal = page.getByRole('region', { name: '이번 장소 기록' });
  await stages.getByRole('button', { name: '저널', exact: true }).click();
  await journal.getByRole('textbox', { name: '장소 이름 (선택)' }).fill('입구 묘실');
  const light = journal.getByRole('checkbox', { name: '광원 −1' });
  await light.check();
  // Phones hide the site tab bar in play mode, so leave through the address bar.
  await page.goto('/bestiary');
  await expect(page).toHaveURL('/bestiary');
  await page.getByRole('link', { name: '플레이 모드', exact: true }).click();
  await page.reload();
  await expect(journal.getByRole('textbox', { name: '장소 이름 (선택)' })).toHaveValue('입구 묘실');
  await expect(light).toBeChecked();
  await expect(journal).toContainText('다음 긴장 주사위 D8');
  await journal.getByRole('button', { name: '다음 장소', exact: true }).click();
  await room.click();
  await expect(explore.getByRole('link', { name: '광원 2 소모' })).toBeVisible();
  await expect(tension).toHaveValue('8');
  await tensionValue.fill('2');
  await tensionValue.press('Enter');
  await stages.getByRole('button', { name: '저널', exact: true }).click();
  await expect(journal.getByRole('checkbox', { name: '광원 −2' })).not.toBeChecked();
  await expect(journal.getByRole('textbox', { name: '장소 이름 (선택)' })).toHaveValue('');
  await journal.getByRole('button', { name: '다음 장소', exact: true }).click();
  await room.click();
  await expect(tension).toHaveValue('6');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
});
