/** Hangul spellings for every English word in the given names/aliases that the dictionary knows. */
export function phoneticAliases(texts: string[]): string[] {
  const out = new Set<string>();
  const words = texts.join(' ').toLowerCase().match(/[a-z]+/g) ?? [];
  const seen = new Set(words);
  for (const w of seen) for (const h of PHONETIC[w] ?? []) out.add(h);
  // two-word terms read as one ("텐션다이", "위크스팟", "대미지풀")
  const pairs: [string, string][] = [
    ['tension', 'die'],
    ['weak', 'spot'],
    ['damage', 'pool'],
    ['defensive', 'move'],
    ['growing', 'darkness'],
    ['icon', 'caller'],
    ['umbra', 'phantom'],
    ['abyssal', 'reaver'],
  ];
  for (const [a, b] of pairs)
    if (seen.has(a) && seen.has(b)) for (const x of PHONETIC[a]) for (const y of PHONETIC[b]) out.add(`${x} ${y}`);
  return [...out];
}
